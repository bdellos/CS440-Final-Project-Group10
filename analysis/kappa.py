"""Cohen's kappa on the held-out set (#47): agent vs each researcher and researcher vs researcher,
for both taxonomies, plus the agents' second rater (skeptic) where it exists.

    .venv/Scripts/python analysis/kappa.py                  # from labels/dump.sql (the committed labels)
    .venv/Scripts/python analysis/kappa.py --out analysis/kappa.md
    .venv/Scripts/python analysis/kappa.py --db labels/labels.db

Which runs: every finished run with purpose 'heldout' on the samples `heldout` (purpose) and
`heldout-repos` (context), with the frozen codebook version of its taxonomy. One run per rater
(the latest, if a rater has several).

Agreement is computed on the items both raters labeled:
  - Cohen's kappa with each item's label SET as one nominal value, so {write-code, write-tests}
    only matches the same two labels (strict; most items have one label);
  - exact agreement (share of identical label sets) and how many items had more than one label;
  - per category, a binary kappa (has the label / doesn't), to show which categories are reliable.
  - where they differ: every pair of label sets the two raters gave the same item, most frequent
    first (a confusion list; the off-diagonal of the confusion matrix).
Kappa is undefined (shown as n/a) when both raters use a single value for every item.
"""
import argparse
import sqlite3
import sys
from collections import Counter
from itertools import combinations
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DUMP = ROOT / "labels/dump.sql"
SAMPLES = {"purpose": "heldout", "context": "heldout-repos"}


def cohen_kappa(a: list, b: list):
    """Cohen's kappa for two equal-length lists of nominal values; None if undefined."""
    if len(a) != len(b) or not a:
        raise ValueError("need two non-empty lists of the same length")
    n = len(a)
    po = sum(x == y for x, y in zip(a, b)) / n
    ca, cb = Counter(a), Counter(b)
    pe = sum(ca[k] * cb[k] for k in ca.keys() | cb.keys()) / (n * n)
    return None if pe == 1 else (po - pe) / (1 - pe)


def load(db: Path | None):
    if db:
        con = sqlite3.connect(f"{db.resolve().as_uri()}?mode=ro", uri=True)
    else:
        con = sqlite3.connect(":memory:")
        con.executescript(DUMP.read_text(encoding="utf-8"))
    return con


def heldout_runs(con, taxonomy: str) -> dict:
    """rater -> run_id: the latest finished held-out run of each rater on the frozen codebook."""
    rows = con.execute(
        """SELECT r.rater, MAX(r.run_id) FROM runs r JOIN samples s USING (sample_id)
           JOIN codebook_versions v ON v.codebook_version_id = r.codebook_version_id
           WHERE s.name = ? AND r.taxonomy = ? AND r.purpose = 'heldout' AND r.finished_at IS NOT NULL
             AND v.frozen = 1
           GROUP BY r.rater ORDER BY r.rater""", (SAMPLES[taxonomy], taxonomy)).fetchall()
    return dict(rows)


def labels_of(con, run_id: int) -> dict:
    """item_id -> frozenset of category keys."""
    out = {}
    for item, cat in con.execute("SELECT a.item_id, l.category_key FROM annotations a "
                                 "JOIN annotation_labels l USING (annotation_id) WHERE a.run_id = ?", (run_id,)):
        out.setdefault(item, set()).add(cat)
    return {k: frozenset(v) for k, v in out.items()}


def compare(x: dict, y: dict) -> dict:
    items = sorted(x.keys() & y.keys())
    if not items:
        return {"n": 0}
    a, b = [x[i] for i in items], [y[i] for i in items]
    cats = sorted(set().union(*a, *b))
    per_cat = {c: cohen_kappa([c in s for s in a], [c in s for s in b]) for c in cats}
    return {"n": len(items), "kappa": cohen_kappa(a, b),
            "exact": sum(s == t for s, t in zip(a, b)) / len(items),
            "multi": sum(len(s) > 1 or len(t) > 1 for s, t in zip(a, b)),
            "per_category": per_cat, "uses": {c: (sum(c in s for s in a), sum(c in s for s in b)) for c in cats}}


def confusions(x: dict, y: dict) -> list:
    """[(count, labels of x, labels of y)] for the shared items where the label sets differ, most frequent first."""
    pairs = Counter((" + ".join(sorted(x[i])), " + ".join(sorted(y[i]))) for i in x.keys() & y.keys() if x[i] != y[i])
    return [(n, a, b) for (a, b), n in sorted(pairs.items(), key=lambda kv: (-kv[1], kv[0]))]


def fmt(k):
    return "n/a" if k is None else f"{k:.2f}"


def report(con) -> str:
    out = ["# Held-out agreement (Cohen's kappa)", "",
           "Generated by `analysis/kappa.py` from the stored labels. Kappa treats each item's label set as one "
           "value; per-category kappa is binary (label present or not).", ""]
    for taxonomy in ("purpose", "context"):
        runs = heldout_runs(con, taxonomy)
        out += [f"## {taxonomy.capitalize()} (sample `{SAMPLES[taxonomy]}`)", ""]
        if len(runs) < 2:
            out += [f"Not enough raters yet: {', '.join(f'{r} (run {i})' for r, i in runs.items()) or 'none'}.", ""]
            continue
        labels = {r: labels_of(con, i) for r, i in runs.items()}
        out += ["| Pair | Runs | Items | Kappa | Exact agreement | Items with >1 label |",
                "|---|---|---|---|---|---|"]
        details = []
        for r1, r2 in combinations(runs, 2):
            c = compare(labels[r1], labels[r2])
            if not c["n"]:
                out.append(f"| {r1} vs {r2} | {runs[r1]}, {runs[r2]} | 0 | n/a | n/a | n/a |")
                continue
            out.append(f"| {r1} vs {r2} | {runs[r1]}, {runs[r2]} | {c['n']} | {fmt(c['kappa'])} | "
                       f"{c['exact']:.0%} | {c['multi']} |")
            details += ["", f"### {taxonomy}: {r1} vs {r2}, per category", "",
                        f"| Category | Uses ({r1}) | Uses ({r2}) | Kappa |", "|---|---|---|---|"]
            details += [f"| `{cat}` | {u[0]} | {u[1]} | {fmt(c['per_category'][cat])} |"
                        for cat, u in c["uses"].items()]
            conf = confusions(labels[r1], labels[r2])
            if conf:
                details += ["", f"### {taxonomy}: {r1} vs {r2}, where they differ "
                            f"({sum(n for n, _, _ in conf)} of {c['n']} items)", "",
                            f"| Items | {r1} | {r2} |", "|---|---|---|"]
                details += [f"| {n} | {a} | {b} |" for n, a, b in conf]
        out += details + [""]
    return "\n".join(out)


def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--db", type=Path, help="read a labels.db instead of labels/dump.sql")
    p.add_argument("--out", type=Path, help="also write the report to this Markdown file")
    a = p.parse_args(argv)
    text = report(load(a.db))
    print(text)
    if a.out:
        a.out.write_text(text + "\n", encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
